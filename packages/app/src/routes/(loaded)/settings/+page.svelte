<script lang="ts">
	import * as Form from '$lib/components/ui/form';
	import { Button } from '$lib/components/ui/button';
	import { FileSelection, Checkbox, SelectLocale } from '$lib/components/ui/input';
	import { app } from '$core/app/context';
	import { settings } from '$core/config/settings.svelte';
	import { antiCheat } from '$core/app/features/anti-cheat';
	import {
		defaultGameDirPath,
		defaultWarningsLogDir,
		detectGameDir,
		detectWarningsLog,
		validateGameDir,
		validateWarningsLog,
		type PathValidation
	} from '$core/config/paths';
	import dayjs from '$lib/dayjs';
	import ImportIcon from 'phosphor-svelte/lib/DownloadSimpleIcon';
	import ExportIcon from 'phosphor-svelte/lib/ExportIcon';
	import ArchiveIcon from 'phosphor-svelte/lib/ArchiveIcon';
	import ArrowSquareOutIcon from 'phosphor-svelte/lib/ArrowSquareOutIcon';
	import MagnifyingGlassIcon from 'phosphor-svelte/lib/MagnifyingGlassIcon';
	import CheckCircleIcon from 'phosphor-svelte/lib/CheckCircleIcon';
	import WarningCircleIcon from 'phosphor-svelte/lib/WarningCircleIcon';
	import { useI18n } from '$lib/i18n';
	import { exists } from '@tauri-apps/plugin-fs';
	import { openUrl, revealItemInDir } from '@tauri-apps/plugin-opener';
	import { dirname } from '@tauri-apps/api/path';
	import { watch } from 'runed';
	import { onMount } from 'svelte';

	const { t } = useI18n();
	const privacyUrl = 'https://coh1stats.com/privacy';

	let backupDir = $state('');
	let lastBackupAt = $state<Date | null>(settings.backup.lastBackupAt);
	let isBackingUp = $state(false);
	let logValidation = $state<PathValidation>({ valid: false });
	let dirValidation = $state<PathValidation>({ valid: false });
	let isDetecting = $state(false);
	let expectedLogDir = $state('');
	let expectedGameDir = $state('');

	$effect(() => {
		settings.paths.backupDir().then((dir) => {
			backupDir = dir;
		});
	});

	watch(
		() => app.settings.companyOfHeroesConfigPath,
		(path) => {
			validateWarningsLog(path).then((result) => {
				logValidation = result;
			});
		}
	);

	watch(
		() => app.settings.companyOfHeroesInstallationPath,
		(path) => {
			validateGameDir(path).then((result) => {
				dirValidation = result;
			});
		}
	);

	const detectPaths = async () => {
		isDetecting = true;
		try {
			expectedLogDir = await defaultWarningsLogDir();
			expectedGameDir = await defaultGameDirPath();
			const [log, game] = await Promise.all([detectWarningsLog(), detectGameDir()]);
			if (log) {
				const current = app.settings.companyOfHeroesConfigPath;
				const currentOk = current ? (await validateWarningsLog(current)).valid : false;
				if (!current || !currentOk) {
					app.settings.companyOfHeroesConfigPath = log;
				}
			}

			if (game) {
				expectedGameDir = game;
				const current = app.settings.companyOfHeroesInstallationPath;
				const currentOk = current ? (await validateGameDir(current)).valid : false;
				if (!current || !currentOk) {
					app.settings.companyOfHeroesInstallationPath = game;
				}
			}
		} finally {
			isDetecting = false;
		}
	};

	const revealPath = async (selected: string, fallback: string) => {
		const candidates = [selected, fallback].filter(Boolean);
		for (const candidate of candidates) {
			if (!(await exists(candidate))) {
				continue;
			}

			try {
				await revealItemInDir(candidate);
				return;
			} catch {
				try {
					await revealItemInDir(await dirname(candidate));
					return;
				} catch {
					// try the next candidate
				}
			}
		}
		app.toast.error(t('Could not open this location. Use Select to browse to it.'));
	};

	onMount(() => {
		void detectPaths();
	});

	const backupNow = async () => {
		isBackingUp = true;
		try {
			await settings.backup.backupNow('manual');
			lastBackupAt = settings.backup.lastBackupAt;
			if (settings.backup.lastError) {
				app.toast.error(t('Backup failed: {message}', { message: settings.backup.lastError }));
			} else {
				app.toast.success(t('Backup created.'));
			}
		} finally {
			isBackingUp = false;
		}
	};
</script>

<Form.Root>
	<Form.Group label={t('Language')} description={t('Choose the language used in the app.')}>
		<SelectLocale bind:value={app.settings.locale} />
	</Form.Group>
	<Form.Group
		label={t('Launch at startup')}
		description={t(
			'Enable or disable launching the application automatically when your system starts.'
		)}
	>
		<Checkbox label={t('Enabled')} bind:checked={app.settings.autostart} />
	</Form.Group>
	<Form.Group
		label={t('Close to tray')}
		description={t(
			'Keep the app running in the system tray when you close the window so match tracking and overlays stay active. Use Quit from the tray menu to fully exit.'
		)}
	>
		<Checkbox label={t('Enabled')} bind:checked={app.settings.closeToTray} />
	</Form.Group>
	<Form.Group
		label={t('Company of Heroes warnings.log')}
		description={t(
			'Select the warnings.log file generated by Company of Heroes. The app needs this file to detect your games.'
		)}
		layout="stacked"
	>
		<FileSelection
			name="pathToConfig"
			bind:value={app.settings.companyOfHeroesConfigPath}
			filters={[{ name: 'warnings.log', extensions: ['log'] }]}
			defaultPath={app.settings.companyOfHeroesConfigPath || expectedLogDir}
			showStatus={false}
		/>
		<div
			class={[
				'flex items-center gap-1 text-sm',
				logValidation.valid ? 'text-green-500' : 'text-red-500'
			]}
		>
			{#if logValidation.valid}
				<CheckCircleIcon weight="duotone" size={18} />
				{t('warnings.log found')}
			{:else}
				<WarningCircleIcon weight="duotone" size={18} />
				{logValidation.reason ?? t('Select your warnings.log')}
			{/if}
		</div>
		{#snippet footer()}
			<Button
				variant="secondary"
				size="sm"
				type="button"
				loading={isDetecting}
				onclick={() => detectPaths()}
			>
				<MagnifyingGlassIcon size={16} />
				{t('Look again')}
			</Button>
			<Button
				variant="secondary"
				size="sm"
				type="button"
				onclick={() => revealPath(app.settings.companyOfHeroesConfigPath, expectedLogDir)}
			>
				<ArrowSquareOutIcon size={16} />
				{t('Show in Explorer')}
			</Button>
		{/snippet}
	</Form.Group>
	<Form.Group
		label={t('Company of Heroes installation folder')}
		description={t(
			'Select the root installation folder of Company of Heroes (contains RelicCOH.exe).'
		)}
		layout="stacked"
	>
		<FileSelection
			name="pathToInstallation"
			directory
			bind:value={app.settings.companyOfHeroesInstallationPath}
			defaultPath={app.settings.companyOfHeroesInstallationPath || expectedGameDir}
			showStatus={false}
		/>
		<div
			class={[
				'flex items-center gap-1 text-sm',
				dirValidation.valid ? 'text-green-500' : 'text-red-500'
			]}
		>
			{#if dirValidation.valid}
				<CheckCircleIcon weight="duotone" size={18} />
				{t('Installation found')}
			{:else}
				<WarningCircleIcon weight="duotone" size={18} />
				{dirValidation.reason ?? t('Select your installation folder')}
			{/if}
		</div>
		{#snippet footer()}
			<Button
				variant="secondary"
				size="sm"
				type="button"
				loading={isDetecting}
				onclick={() => detectPaths()}
			>
				<MagnifyingGlassIcon size={16} />
				{t('Look again')}
			</Button>
			<Button
				variant="secondary"
				size="sm"
				type="button"
				onclick={() => revealPath(app.settings.companyOfHeroesInstallationPath, expectedGameDir)}
			>
				<ArrowSquareOutIcon size={16} />
				{t('Show in Explorer')}
			</Button>
		{/snippet}
	</Form.Group>
	<Form.Group label={t('Fair play')} />
	<Form.Group label={t('Fair play checks')}>
		{#snippet description()}
			{t(
				"During a match the app uses Company of Heroes' own Print Screen (never your Windows desktop) and checks for known cheat processes. These are uploaded for review and later analysis."
			)}
			<Button variant="link" class="h-auto px-0" type="button" onclick={() => openUrl(privacyUrl)}>
				{t('Privacy policy')}
			</Button>
		{/snippet}
		<Checkbox label={t('Enabled')} bind:checked={antiCheat.settings.enabled} />
	</Form.Group>
	<Form.Group
		label={t('All-chat announce')}
		description={t(
			'Posts "[FAIRPLAY] Supervised by coh1stats.com" in all-chat at match start so other players can see fair play is on. Off until you enable it.'
		)}
	>
		<Checkbox
			label={t('Enabled')}
			bind:checked={antiCheat.settings.announceInChat}
			disabled={!antiCheat.settings.enabled}
			class="disabled:cursor-not-allowed"
		/>
	</Form.Group>
	<Form.Group label={t('Import / Export')} />
	<Form.Group
		label={t('Import configuration')}
		description={t(
			'Import a configuration JSON file to restore your settings. The file is validated first and applied immediately; nothing changes when the file is invalid.'
		)}
	>
		{#snippet footer()}
			<Button variant="secondary" type="button" class="w-fit" onclick={() => app.importSettings()}>
				<ImportIcon size={16} />
				{t('Import')}
			</Button>
		{/snippet}
	</Form.Group>
	<Form.Group
		label={t('Export configuration')}
		description={t(
			'Export your full configuration (including your account and feature settings) to a JSON file.'
		)}
	>
		{#snippet footer()}
			<Button variant="secondary" type="button" class="w-fit" onclick={() => app.exportSettings()}>
				<ExportIcon size={16} />
				{t('Export')}
			</Button>
		{/snippet}
	</Form.Group>
	<Form.Group label={t('Backups')} />
	<Form.Group label={t('Automatic backups')}>
		{#snippet description()}
			{t(
				"Your settings and account are automatically backed up to {dir}, outside the app's data folder. They survive updates, even when you choose to remove all app data.",
				{ dir: backupDir }
			)}
			{#if lastBackupAt}
				<br />{t('Last backup: {date}', {
					date: dayjs(lastBackupAt).format('DD MMM YYYY, HH:mm:ss')
				})}
			{/if}
		{/snippet}
		{#snippet footer()}
			<Button
				variant="secondary"
				type="button"
				class="w-fit"
				onclick={backupNow}
				loading={isBackingUp}
			>
				<ArchiveIcon size={16} />
				{t('Backup now')}
			</Button>
		{/snippet}
	</Form.Group>
</Form.Root>
