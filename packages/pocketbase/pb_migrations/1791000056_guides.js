function exists(app, name) {
	try {
		app.findCollectionByNameOrId(name);
		return true;
	} catch {
		return false;
	}
}

/**
 * Self relations need the collection's id, so they (and the indexes that use them) are added
 * after the first save.
 */
function addSelfRelation(app, name, field, indexes = []) {
	const collection = app.findCollectionByNameOrId(name);
	if (!collection.fields.getByName(field)) {
		collection.fields.add(new Field(relation(name, field, collection.id)));
		collection.indexes = [...collection.indexes, ...indexes];
		app.save(collection);
	}
}

function setRoles(app, values) {
	const users = app.findCollectionByNameOrId('_pb_users_auth_');
	const role = users.fields.getByName('role');
	role.values = values;
	app.save(users);
}

const SLUG = '^[a-z0-9-]+$';

migrate(
	(app) => {
		setRoles(app, ['admin', 'moderator', 'host', 'editor']);

		if (!exists(app, 'guide_categories')) {
			const c = 'guide_categories';
			app.save(
				new Collection({
					createRule: null,
					deleteRule: null,
					updateRule: null,
					listRule: null,
					viewRule: null,
					name: c,
					type: 'base',
					indexes: [],
					fields: [
						id(c),
						text(c, 'name', 80, true),
						text(c, 'slug', 80, true, SLUG),
						number(c, 'sort'),
						...autodates(c)
					]
				})
			);
			addSelfRelation(app, c, 'parent', [
				'CREATE UNIQUE INDEX `idx_guide_categories_parent_slug` ON `guide_categories` (`parent`, `slug`)',
				'CREATE INDEX `idx_guide_categories_parent_sort` ON `guide_categories` (`parent`, `sort`)'
			]);
		}

		if (!exists(app, 'guides')) {
			const c = 'guides';
			const categories = app.findCollectionByNameOrId('guide_categories');
			app.save(
				new Collection({
					createRule: null,
					deleteRule: null,
					updateRule: null,
					listRule: null,
					viewRule: null,
					name: c,
					type: 'base',
					indexes: [
						'CREATE UNIQUE INDEX `idx_guides_language_slug` ON `guides` (`language`, `slug`)',
						'CREATE INDEX `idx_guides_status_language_published` ON `guides` (`status`, `language`, `publishedAt`)',
						'CREATE INDEX `idx_guides_category` ON `guides` (`category`)',
						'CREATE INDEX `idx_guides_author_updated` ON `guides` (`author`, `updated`)'
					],
					fields: [
						id(c),
						text(c, 'title', 200),
						text(c, 'slug', 140, true, SLUG),
						text(c, 'excerpt', 300),
						text(c, 'body', 100000),
						image(c, 'cover', 1, 5 * 1024 * 1024, ['1200x630', '600x0']),
						image(c, 'images', 30, 5 * 1024 * 1024, ['1200x0', '800x0']),
						relation(c, 'category', categories.id),
						select(c, 'language', ['en', 'es', 'ko']),
						select(c, 'status', ['draft', 'published']),
						date(c, 'publishedAt'),
						text(c, 'seoTitle', 70),
						text(c, 'seoDescription', 160),
						bool(c, 'noindex'),
						relation(c, 'author', '_pb_users_auth_'),
						relation(c, 'updatedBy', '_pb_users_auth_'),
						...autodates(c)
					]
				})
			);
			addSelfRelation(app, c, 'translationOf');
		}
	},
	(app) => {
		for (const name of ['guides', 'guide_categories']) {
			try {
				app.delete(app.findCollectionByNameOrId(name));
			} catch {
				// already gone
			}
		}

		setRoles(app, ['admin', 'moderator', 'host']);
	}
);
