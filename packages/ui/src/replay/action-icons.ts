/** Icon key for an action, or `null` (move/capture/unknown objects). Prefers a stored `action.icon`. */
export function actionIconKey(
	action: Pick<ReplayAction, 'objectID' | 'command' | 'icon' | 'cancelled'>
): string | null {
	if (action.icon !== undefined) {
		return action.icon;
	}

	const type = action.command?.type;
	if (isCancelAction(action)) {
		// Show what was cancelled; the timeline adds a cancel mark on top.
		const order = action.cancelled;
		return order
			? actionIconKey({ objectID: order.objectID, command: order.command ?? undefined })
			: null;
	}

	if (!type || action.objectID == null) {
		return null;
	}

	// Reinforce uses squad blueprint IDs, so it shares the UNIT icons.
	return ACTION_ICONS[type === 'REINFORCE' ? 'UNIT' : type]?.[action.objectID] ?? null;
}
